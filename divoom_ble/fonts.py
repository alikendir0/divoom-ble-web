def render_text(text: str, font: dict[str, list[list[bool]]], spacing: int = 1) -> list[list[bool]]:
    """Return rows of booleans for `text`; unknown characters render as '?'."""
    height = len(next(iter(font.values())))
    rows: list[list[bool]] = [[] for _ in range(height)]
    for i, ch in enumerate(text.upper()):
        glyph = font.get(ch) or font["?"]
        for y in range(height):
            if i:
                rows[y].extend([False] * spacing)
            rows[y].extend(glyph[y])
    return rows
