def _compile(table: dict[str, list[str]]) -> dict[str, list[list[bool]]]:
    out = {}
    for ch, rows in table.items():
        w = max(len(r) for r in rows)
        out[ch] = [[c == "#" for c in r.ljust(w)] for r in rows]
    return out


